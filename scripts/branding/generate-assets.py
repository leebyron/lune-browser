#!/usr/bin/env python3
"""Generate Lune's vector artwork from the approved geometry and palettes."""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def geometry(config):
    radius = config['outer_radius']
    offset = config['center_offset']
    height = math.sqrt(radius * radius - offset * offset)
    reach = radius + offset - 2 * offset * config['width_multiplier']
    inner = (reach * reach + height * height) / (2 * reach)
    return radius, height, inner


def paths(config):
    radius, height, inner = geometry(config)
    top, bottom = 150 - height, 150 + height
    return [f'M150 {top:.6f} A{radius} {radius} 0 1 {sweep} 150 {bottom:.6f} '
            f'A{inner:.6f} {inner:.6f} 0 0 {1-sweep} 150 {top:.6f} Z'
            for sweep in (0, 1)]


def svg(data, tile=True, mode=None, favicon=False):
    def colors(p):
        return f'.ground{{fill:{p["ground"]}}}.left{{fill:{p["left"]}}}.right{{fill:{p["right"]}}}'
    style = colors(data[mode or 'light'])
    if mode is None:
        style += '@media(prefers-color-scheme:dark){' + colors(data['dark']) + '}'
    viewbox = '0 0 1024 1024' if tile else '212 245.6 600 532.8'
    size = 'width="1024" height="1024"' if tile else 'width="600" height="533"'
    tile_rect = '<rect class="ground" x="64" y="64" width="896" height="896" rx="200"/>' if tile else ''
    transform = 'translate(152 152) scale(2.4)'
    if favicon:
        # Square canvas tightly fitted to the wider dimension of the mark.
        extent = data['geometry']['outer_radius'] + data['geometry']['center_offset']
        viewbox = f'{150-extent:g} {150-extent:g} {2*extent:g} {2*extent:g}'
        size = 'width="256" height="256"'
        tile_rect = ''
        transform = ''
    left, right = paths(data['geometry'])
    result = f'''<svg xmlns="http://www.w3.org/2000/svg" {size} viewBox="{viewbox}">
  <title>Lune</title>
  <desc>Paired lunes. Chlorophyll Daylight and Pelagic Signal.</desc>
  <style>{style}</style>
  {tile_rect}
  <g transform="{transform}">
    <path class="left" d="{left}"/>
    <path class="right" d="{right}"/>
  </g>
</svg>
'''
    return '\n'.join(line.rstrip() for line in result.splitlines()) + '\n'


def vector(data, colored=False):
    radius, height, inner = geometry(data['geometry'])
    # Monochrome UI symbols fill their square slot horizontally, like the
    # favicon. Keep the mark proportional and centered; app tiles retain inset.
    extent = data['geometry']['outer_radius'] + data['geometry']['center_offset']
    scale = 0.6 if colored else 300 / (2 * extent)
    offset = 38 if colored else 150 - 150 * scale
    x, top, bottom = offset + 150 * scale, offset + (150-height)*scale, offset + (150+height)*scale
    def color(value):
        return ', '.join('0x' + value[i:i+2] for i in (1, 3, 5))
    result = '// Generated by scripts/branding/generate-assets.py.\n'
    result += f'CANVAS_DIMENSIONS, {256 if colored else 300},\n'
    if colored:
        result += f'PATH_COLOR_ARGB, 0xFF, {color(data["dark"]["ground"])},\nROUND_RECT, 16, 16, 224, 224, 50,\n'
    for sweep, key in ((0, 'left'), (1, 'right')):
        result += 'NEW_PATH,\n'
        if colored:
            result += f'PATH_COLOR_ARGB, 0xFF, {color(data["dark"][key])},\n'
        result += (f'MOVE_TO, {x:.6f}f, {top:.6f}f,\n'
                   f'ARC_TO, {radius*scale:.6f}f, {radius*scale:.6f}f, 0, 1, {sweep}, {x:.6f}f, {bottom:.6f}f,\n'
                   f'ARC_TO, {inner*scale:.6f}f, {inner*scale:.6f}f, 0, 0, {1-sweep}, {x:.6f}f, {top:.6f}f,\nCLOSE,\n')
    return result


def outputs(data):
    mono = ' '.join(paths(data['geometry']))
    return {
        'branding/lune.svg': svg(data),
        'branding/lune-light.svg': svg(data, mode='light'),
        'branding/lune-dark.svg': svg(data, mode='dark'),
        'website/public/assets/lune-icon.svg': svg(data),
        'website/public/assets/lune-mark.svg': svg(data, tile=False),
        'website/public/favicon.svg': svg(data, tile=False, favicon=True),
        'out/branding/internal/product_logo.svg': svg(data),
        'out/branding/internal/product_logo_mono.svg': f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 300"><path fill="currentColor" d="{mono}"/></svg>\n',
        'out/branding/internal/product_logo.icon': vector(data),
        'out/branding/internal/product_logo_color.icon': vector(data, colored=True),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'branding/palettes.json').read_text())
    for name, content in outputs(data).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated artwork: {name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
